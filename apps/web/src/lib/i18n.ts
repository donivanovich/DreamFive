export type TranslationBundle = (typeof TRANSLATIONS)[AppLanguage];

export function formatMsg(template: string, vars: Record<string, string | number>): string {
  let out = template;
  for (const [k, v] of Object.entries(vars)) {
    out = out.replaceAll(`{${k}}`, String(v));
  }
  return out;
}

export function getLocaleCode(lang: AppLanguage): string {
  return lang === 'es' ? 'es-ES' : 'en-US';
}

export function translateLeagueRole(role: LeagueRole, lang: AppLanguage): string {
  return role === 'PRESIDENT'
    ? TRANSLATIONS[lang].common.president
    : TRANSLATIONS[lang].common.member;
}

export function translateLeagueStatus(status: LeagueStatus, lang: AppLanguage): string {
  const c = TRANSLATIONS[lang].common;
  if (status === 'ACTIVE') return c.leagueActiveStatus;
  return c.leagueFinishedStatus;
}

export function translateMarketMode(mode: MarketMode, lang: AppLanguage): string {
  const c = TRANSLATIONS[lang].common;
  return mode === 'GLOBAL_HYBRID' ? c.marketHybrid : c.marketIsolated;
}

export function translateMatchStatus(
  status: MatchStatus | 'FINAL' | 'PROGRAMADO',
  lang: AppLanguage,
): string {
  const c = TRANSLATIONS[lang].common;
  if (status === 'FINAL') return c.finalMatch;
  if (status === 'IN_PROGRESS') return c.liveMatch;
  return c.scheduledMatch;
}

export function translateTradeStatus(
  status: TransferStatus | TradeOffer['status'],
  lang: AppLanguage,
): string {
  const c = TRANSLATIONS[lang].common;
  if (status === 'ACCEPTED' || status === 'Aceptada') return c.acceptedStatus;
  if (status === 'REJECTED' || status === 'Rechazada') return c.rejectedStatus;
  if (status === 'EXPIRED') return c.expiredStatus;
  if (status === 'CANCELLED') return c.cancelledStatus;
  return c.pendingStatus;
}

export function translateInvitationStatus(status: InvitationStatus, lang: AppLanguage): string {
  const c = TRANSLATIONS[lang].common;
  if (status === 'ACCEPTED') return c.acceptedStatus;
  if (status === 'REJECTED') return c.rejectedStatus;
  return c.pendingStatus;
}

export function formatTransferLockBadge(
  remainingMatches: number,
  _reason: TransferBlockReason,
  lang: AppLanguage,
): string {
  const t = TRANSLATIONS[lang].transfersPage;
  if (remainingMatches <= 1) {
    return t.lockedOneMatchBadge;
  }
  return formatMsg(t.lockedMatchesBadge, { count: remainingMatches });
}
